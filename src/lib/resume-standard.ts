/* ═══════════════════════ 写作规范 ═══════════════════════ */

export const RESUME_WRITING_RULES = `【写作规范】
1. 每条经历写成「动作 + 方法 + 可量化结果」，例如「重构订单链路，P99 从 820ms 降到 210ms」。
2. 数字优先于形容词：百分比、金额、时长、用户量、排名、节点数、台数。能写就写。
3. 一条 = 一行；超过两行就拆开或删掉，不要把一整段话堆进一条里。
4. 不虚构：用户没提供的经历、数字、证书、时间一律不编，宁可留空让用户补。
5. 写进去的每一项技术和成果，用户都要能在面试里接住追问（为什么用它 / 不用会怎样 / 出过什么故障）；
   接不住的就换成他真做过的。
6. 按目标岗位定制：优先突出与 JD 匹配的技能与经历，措辞向 JD 靠拢；无关的旧经历放后面或删掉。
7. 少说空话：「认真负责、学习能力强」这类形容词不占篇幅，除非后面有事实支撑。`;

/* ═══════════════════════ 结构与排版 ═══════════════════════ */

export const RESUME_LAYOUT_RULES = `【结构与排版】
1. 板块从下面挑，不必每个都要：基本信息 → 求职意向 → 教育背景 → 工作经历 → 项目经历 →
   专业技能 → 技能证书 → 自我评价。学生以教育背景和在校/项目经历为主，有工作经验则以工作经历为主。
2. 单栏排版：不用表格、不用多列布局。求职筛选系统（ATS）按单栏解析简历，多栏会被读乱。
3. 一页 A4 为佳：正文 10.5pt、页边距 1–1.5cm。内容超页时先删掉与目标岗位无关的经历，
   不要一路缩小字号。
4. 日期用日期字段并右对齐，不要写在正文句子里。
5. 主题色全文统一，只用于标题、分隔线与强调，不要五颜六色。`;

/** 完整规范：直接拼进 system 提示词 */
export const RESUME_STANDARD_PROMPT = `${RESUME_WRITING_RULES}\n\n${RESUME_LAYOUT_RULES}`;

